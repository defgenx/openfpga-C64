#!/usr/bin/env python3
"""Prepare C64_MiSTer's VHDL for ghdl: copy the sources to work/vhdl, patch them, and
turn the ROMs (.mif) into hex files plus small Verilog ROM modules (work/dprom_*.v).

  * cpu_6510.vhd: VHDL-87 style `work.T65` instantiation -> `entity work.T65`
  * fpga64_buslogic.vhd: every `entity work.dprom generic map ("x.mif", N)` becomes a
    component `dprom_x` implemented in Verilog (ghdl cannot read the .mif)
"""
import re, os, shutil

here = os.path.dirname(os.path.abspath(__file__))
rtl = os.path.normpath(os.path.join(here, '../../src/fpga/C64_MiSTer/rtl'))
work = os.path.join(here, 'work')
vh = os.path.join(work, 'vhdl')
rom = os.path.join(work, 'roms')
os.makedirs(vh, exist_ok=True)
os.makedirs(rom, exist_ok=True)

srcs = ['t65/T65_Pack.vhd', 't65/T65_ALU.vhd', 't65/T65_MCode.vhd', 't65/T65.vhd', 'cpu_6510.vhd',
        'video_vicII_656x.vhd', 'video_sync.vhd', 'fpga64_rgbcolor.vhd', 'fpga64_keyboard.vhd',
        'spram.vhd', 'fpga64_buslogic.vhd', 'fpga64_sid_iec.vhd']
for s in srcs:
    shutil.copy(os.path.join(rtl, s), os.path.join(vh, os.path.basename(s)))

p = os.path.join(vh, 'cpu_6510.vhd')
t = open(p).read()
t = t.replace('cpu: work.T65', 'cpu: entity work.T65')
# VHDL-93 needs a static port actual
t = t.replace('Res_n   => not reset,', 'Res_n   => res_n_i,')
t = t.replace('\tsignal accessIO : std_logic;\nbegin', '\tsignal accessIO : std_logic;\n\tsignal res_n_i : std_logic;\nbegin\n\tres_n_i <= not reset;')
assert 'res_n_i <=' in t
open(p, 'w').write(t)

# ghdl wants complete case choices on unsigned selectors; Quartus does not
p = os.path.join(vh, 'fpga64_rgbcolor.vhd')
t = open(p).read()
t = re.sub(r'end case;', 'when others => r <= X"00"; g <= X"00"; b <= X"00";\nend case;', t)
open(p, 'w').write(t)

p = os.path.join(vh, 'fpga64_sid_iec.vhd')
t = open(p).read()
t = t.replace('when "11" => turbo_m <= "111"; -- unused', 'when others => turbo_m <= "111"; -- unused')
open(p, 'w').write(t)


def mif2hex(mif, hexf, bits):
    mem = [0] * (1 << bits)
    inside = False
    for line in open(mif):
        line = line.strip()
        if line.startswith('CONTENT BEGIN'):
            inside = True
            continue
        if line.startswith('END'):
            break
        if not inside:
            continue
        m = re.match(r'([0-9A-Fa-f]+)\s*:\s*([0-9A-Fa-f ]+);', line)
        if m:
            for k, v in enumerate(m.group(2).split()):
                mem[int(m.group(1), 16) + k] = int(v, 16)
            continue
        m = re.match(r'\[([0-9A-Fa-f]+)\.\.([0-9A-Fa-f]+)\]\s*:\s*([0-9A-Fa-f]+);', line)
        if m:
            for a in range(int(m.group(1), 16), int(m.group(2), 16) + 1):
                mem[a] = int(m.group(3), 16)
    open(hexf, 'w').write(''.join('%02x\n' % v for v in mem))


p = os.path.join(vh, 'fpga64_buslogic.vhd')
t = open(p).read()
comps = {}


def repl(m):
    inst = m.group(1)
    name = os.path.splitext(os.path.basename(m.group(2)))[0]
    comps[name] = int(m.group(3))
    return '%s: dprom_%s\n\tport map (' % (inst, name)


t, n = re.subn(r'(\w+):\s*entity work\.dprom\s*generic map \("([^"]+)",\s*(\d+)\)\s*port map\s*\(', repl, t)
assert n == 6, n
decl = ''
for name, bits in comps.items():
    decl += '''component dprom_%s
	port (
		wrclock   : in  std_logic;
		wraddress : in  std_logic_vector(%d downto 0) := (others => '0');
		data      : in  std_logic_vector(7 downto 0) := (others => '0');
		wren      : in  std_logic := '0';
		rdclock   : in  std_logic;
		rdaddress : in  std_logic_vector(%d downto 0);
		q         : out std_logic_vector(7 downto 0)
	);
end component;
''' % (name, bits - 1, bits - 1)
    mif2hex(os.path.join(rtl, 'roms', name + '.mif'), os.path.join(rom, name + '.hex'), bits)
    open(os.path.join(work, 'dprom_%s.v' % name), 'w').write('''// generated by gen_vhdl.py: ROM %s (%d address bits), writable like dprom.vhd
module dprom_%s (
	input         wrclock,
	input  [%d:0] wraddress,
	input  [7:0]  data,
	input         wren,
	input         rdclock,
	input  [%d:0] rdaddress,
	output reg [7:0] q
);
reg [7:0] mem [0:%d];
initial $readmemh("%s/%s.hex", mem);
always @(posedge wrclock) if (wren) mem[wraddress] <= data;
always @(posedge rdclock) q <= mem[rdaddress];
endmodule
''' % (name, bits, name, bits - 1, bits - 1, (1 << bits) - 1, 'work/roms', name))
m = re.search(r'(signal currentAddr[^\n]*\n)', t)
t = t[:m.end()] + decl + t[m.end():]
open(p, 'w').write(t)
print('vhdl prepared in', vh)
